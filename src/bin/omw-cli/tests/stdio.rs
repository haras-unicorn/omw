//! `omw` standard-stream (`-`, `/dev/stdin`, `/dev/stdout`) integration tests.

mod common;

use predicates::prelude::*;
use tempfile::tempdir;

#[test]
fn schema_streams_json_to_stdout() {
  for target in ["-", "/dev/stdout"] {
    let assert = common::omw()
      .args(["schema", "--output", target])
      .assert()
      .success();
    let stdout = String::from_utf8(assert.get_output().stdout.clone()).unwrap();
    assert!(
      stdout.trim_start().starts_with('{') && stdout.trim_end().ends_with('}'),
      "expected a JSON document on stdout, got: {stdout}"
    );
  }
}

#[test]
fn schema_logs_go_to_stderr_while_data_goes_to_stdout() {
  let assert = common::omw()
    .args(["schema", "--output", "-"])
    .assert()
    .success();
  let output = assert.get_output();
  let stdout = String::from_utf8(output.stdout.clone()).unwrap();
  let stderr = String::from_utf8(output.stderr.clone()).unwrap();
  assert!(stdout.trim_start().starts_with('{'), "got: {stdout}");
  assert!(
    stderr.contains("\"level\":\"INFO\""),
    "logs should be JSONL on stderr, got: {stderr}"
  );
}

#[test]
fn config_reads_from_stdin() {
  for path in ["-", "/dev/stdin"] {
    common::omw()
      .args(["run", "--config", path, "--format", "toml"])
      .write_stdin("[agents]\n")
      .assert()
      .success();
  }
}

#[test]
fn stdin_config_requires_a_format() {
  common::omw()
    .args(["run", "--config", "-"])
    .write_stdin("[agents]\n")
    .assert()
    .failure()
    .stderr(predicate::str::contains("cannot infer"));
}

#[test]
fn scaffold_streams_to_stdout_without_a_path_line() {
  let dir = tempdir().unwrap();
  let config = dir.path().join("omw.toml");
  std::fs::write(&config, "[providers.ghost]\nkind = \"nope\"\n").unwrap();

  let assert = common::omw()
    .args(["scaffold"])
    .arg(&config)
    .args(["--output", "-"])
    .assert()
    .success();
  let stdout = String::from_utf8(assert.get_output().stdout.clone()).unwrap();
  assert!(
    stdout.starts_with("# Generated by"),
    "expected the provenance banner, got: {stdout}"
  );
  // The old bug printed the output path after the config; a stream target must
  // not.
  assert!(
    !stdout.contains("/dev/stdout") && !stdout.contains("\n-\n"),
    "stdout should hold only the config, got: {stdout}"
  );
  assert!(stdout.contains("[providers.ghost]"), "got: {stdout}");
  assert!(stdout.contains("kind = \"mock\""), "got: {stdout}");
}

#[test]
fn scaffold_pipeline_stdin_to_stdout() {
  let assert = common::omw()
    .args(["scaffold", "-", "--format", "toml", "--output", "-"])
    .write_stdin("[providers.ghost]\nkind = \"nope\"\n")
    .assert()
    .success();
  let stdout = String::from_utf8(assert.get_output().stdout.clone()).unwrap();
  assert!(stdout.starts_with("# Generated by"), "got: {stdout}");
  assert!(stdout.contains("kind = \"mock\""), "got: {stdout}");
}
